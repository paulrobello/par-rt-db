// ARC-001: regenerates the Go client's error-code tables from
// wire-corpus/error-codes.json — the canonical {code, httpStatus} table the
// server regenerates from server/src/error.rs::ErrorCode. Two files are
// emitted, both DO-NOT-EDIT:
//
//   - go-client/errors/error_codes_gen.go — the ErrorCode const block, the
//     httpStatus map, and AllCodes(); pinned against the same fixture by
//     go-client/wire/error_codes_test.go (set, status, and order).
//   - go-client/reexports_error_codes_gen.go — the root-package convenience
//     aliases (parrtdb.CodeXxx), one per fixture row.
//
// Run via `make gen-error-codes` (repo root) or `go generate ./...`
// (from go-client/; the directive lives in reexports.go).
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	goformat "go/format"
	"os"
	"strings"
)

type corpusEntry struct {
	Code       string `json:"code"`
	HTTPStatus int    `json:"httpStatus"`
}

type corpusFile struct {
	Codes []corpusEntry `json:"codes"`
}

// constName derives the Go identifier for a wire code: SCHEMA_VIOLATION ->
// CodeSchemaViolation.
func constName(code string) (string, error) {
	var b strings.Builder
	b.WriteString("Code")
	for _, part := range strings.Split(code, "_") {
		if part == "" {
			return "", fmt.Errorf("code %q has an empty _ segment", code)
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(strings.ToLower(part[1:]))
	}
	return b.String(), nil
}

const fileHeader = `// Code generated by go-client/internal/gen/errorcodes from
// wire-corpus/error-codes.json. DO NOT EDIT — regenerate with
// 'make gen-error-codes' after changing the fixture.

`

// renderErrorsTable emits the errors-package table, gofmt-canonical.
func renderErrorsTable(entries []corpusEntry) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(fileHeader)
	fmt.Fprint(&b, `package errors

// One ErrorCode constant per wire-corpus/error-codes.json row, in fixture
// (server enum declaration) order.
const (
`)
	for _, e := range entries {
		name, err := constName(e.Code)
		if err != nil {
			return nil, err
		}
		for _, line := range strings.Split(constComment(e.Code), "\n") {
			fmt.Fprintf(&b, "\t// %s\n", line)
		}
		fmt.Fprintf(&b, "\t%s ErrorCode = %q\n", name, e.Code)
	}
	fmt.Fprint(&b, `)

// httpStatus mirrors wire-corpus/error-codes.json's {code, httpStatus}
// pairs.
var httpStatus = map[ErrorCode]int{
`)
	for _, e := range entries {
		name, err := constName(e.Code)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t%s: %d,\n", name, e.HTTPStatus)
	}
	fmt.Fprint(&b, `}

// AllCodes is the closed set, in fixture order.
func AllCodes() []ErrorCode {
	return []ErrorCode{
`)
	for _, e := range entries {
		name, err := constName(e.Code)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t\t%s,\n", name)
	}
	fmt.Fprint(&b, `	}
}
`)
	return formatSource(b.Bytes())
}

// renderReexports emits the root-package convenience aliases, gofmt-canonical.
func renderReexports(entries []corpusEntry) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(fileHeader)
	fmt.Fprint(&b, `package parrtdb

import "github.com/paulrobello/par-rt-db/go-client/errors"

// One alias per wire-corpus/error-codes.json row, in fixture order — the
// enumerated table itself lives in the errors package (error_codes_gen.go).
const (
`)
	for _, e := range entries {
		name, err := constName(e.Code)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t%s = errors.%s\n", name, name)
	}
	fmt.Fprint(&b, `)
`)
	return formatSource(b.Bytes())
}

// formatSource makes the emitted source gofmt-canonical, dumping the raw
// buffer to stderr when the template is broken so the failure is diagnosable.
func formatSource(src []byte) ([]byte, error) {
	out, err := goformat.Source(src)
	if err != nil {
		os.Stderr.Write(src)
	}
	return out, err
}

// constComment carries semantic doc comments for specific codes; the
// enumeration itself is always generated, this only annotates.
func constComment(code string) string {
	if comment, ok := constComments[code]; ok {
		return comment
	}
	return ""
}

// constComments is the per-code annotation table.
var constComments = map[string]string{
	"READ_ONLY": "CodeReadOnly is the per-database read-only freeze\n" +
		"(PATCH /admin/db/{db}/readonly): client-plane document writes are\n" +
		"rejected while frozen.",
}

func loadCorpus(path string) ([]corpusEntry, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read corpus: %w", err)
	}
	var corpus corpusFile
	if err := json.Unmarshal(raw, &corpus); err != nil {
		return nil, fmt.Errorf("parse corpus: %w", err)
	}
	if len(corpus.Codes) == 0 {
		return nil, fmt.Errorf("corpus %s has no codes", path)
	}
	seen := map[string]bool{}
	for _, e := range corpus.Codes {
		if seen[e.Code] {
			return nil, fmt.Errorf("duplicate code %q in corpus", e.Code)
		}
		seen[e.Code] = true
		if e.HTTPStatus < 100 || e.HTTPStatus > 599 {
			return nil, fmt.Errorf("code %q: httpStatus %d out of range", e.Code, e.HTTPStatus)
		}
		if _, err := constName(e.Code); err != nil {
			return nil, err
		}
	}
	return corpus.Codes, nil
}

func write(path string, src []byte) error {
	if err := os.WriteFile(path, src, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	fmt.Printf("wrote %s\n", path)
	return nil
}

func main() {
	corpus := flag.String("corpus", "../wire-corpus/error-codes.json", "path to wire-corpus/error-codes.json")
	errorsOut := flag.String("errors", "./errors/error_codes_gen.go", "path of the generated errors-package table")
	reexportsOut := flag.String("reexports", "./reexports_error_codes_gen.go", "path of the generated root-package aliases")
	flag.Parse()
	// The generator runs with CWD = go-client/ (the package owning the
	// go:generate directive in reexports.go).
	entries, err := loadCorpus(*corpus)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	table, err := renderErrorsTable(entries)
	if err != nil {
		fmt.Fprintf(os.Stderr, "errors table: %v\n", err)
		os.Exit(1)
	}
	reexports, err := renderReexports(entries)
	if err != nil {
		fmt.Fprintf(os.Stderr, "reexports: %v\n", err)
		os.Exit(1)
	}
	if err := write(*errorsOut, table); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := write(*reexportsOut, reexports); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("(%d codes)\n", len(entries))
}
