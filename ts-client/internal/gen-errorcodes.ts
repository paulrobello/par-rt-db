/**
 * ARC-001 follow-up: regenerates `src/errors_gen.ts` — the `RtDbErrorCode`
 * union and the `ALL_ERROR_CODES` array — from wire-corpus/error-codes.json,
 * the canonical {code, httpStatus} table the server regenerates from
 * `server/src/error.rs::ErrorCode`. Run via `make gen-error-codes-ts`;
 * `make gen-error-codes-ts-check` fails the gate when the committed file
 * disagrees with the fixture. Zero dependencies: plain bun, node:fs only.
 */

import { readFileSync, writeFileSync } from "node:fs";

interface CorpusEntry {
  code: string;
  httpStatus: number;
}

interface CorpusFile {
  codes: CorpusEntry[];
}

function parseArgs(): { corpus: string; out: string } {
  let corpus = "../wire-corpus/error-codes.json";
  let out = "src/errors_gen.ts";
  const args = process.argv.slice(2);
  for (let i = 0; i < args.length; i += 2) {
    const value = args[i + 1];
    if (value === undefined) {
      throw new Error(`flag ${args[i]} needs a value`);
    }
    switch (args[i]) {
      case "--corpus":
        corpus = value;
        break;
      case "--out":
        out = value;
        break;
      default:
        throw new Error(`unknown flag ${args[i]}`);
    }
  }
  return { corpus, out };
}

function loadCorpus(path: string): CorpusEntry[] {
  const corpus = JSON.parse(readFileSync(path, "utf8")) as CorpusFile;
  if (!Array.isArray(corpus.codes) || corpus.codes.length === 0) {
    throw new Error(`corpus ${path} has no codes`);
  }
  const seen = new Set<string>();
  for (const entry of corpus.codes) {
    if (seen.has(entry.code)) {
      throw new Error(`duplicate code ${entry.code} in corpus`);
    }
    if (!/^[A-Z][A-Z0-9_]*$/.test(entry.code)) {
      throw new Error(`code ${entry.code} is not SCREAMING_SNAKE_CASE`);
    }
    if (entry.httpStatus < 100 || entry.httpStatus > 599) {
      throw new Error(`code ${entry.code}: httpStatus ${entry.httpStatus} out of range`);
    }
    seen.add(entry.code);
  }
  return corpus.codes;
}

function render(entries: CorpusEntry[]): string {
  const union = `${entries.map((e) => `  | "${e.code}"`).join("\n")};`;
  const array = entries.map((e) => `  "${e.code}",`).join("\n");
  return `// Code generated by internal/gen-errorcodes.ts from
// wire-corpus/error-codes.json. DO NOT EDIT — regenerate with
// 'make gen-error-codes-ts' after changing the fixture.

/**
 * Every wire error code, one per wire-corpus/error-codes.json row, in fixture
 * (server enum declaration) order.
 */
export type RtDbErrorCode =
${union}

/**
 * Every {@link RtDbErrorCode}, in fixture order — the closed set, generated
 * from the same fixture the server's enum table comes from.
 */
export const ALL_ERROR_CODES: readonly RtDbErrorCode[] = [
${array}
];
`;
}

const { corpus, out } = parseArgs();
const entries = loadCorpus(corpus);
writeFileSync(out, render(entries));
console.log(`wrote ${out} (${entries.length} codes)`);
