//! Patch decision fixtures computed by the production transaction helper.
use crate::error::RtDbError;
use crate::schema::TableDef;
use crate::txn::apply_patch;
use serde_json::{Value, json};

/// Render representative shallow-patch, validation, and null-unset decisions.
pub fn render_patch_semantics_spec() -> Result<String, serde_json::Error> {
    let mut rows = Vec::new();
    for (id, ty, doc, patch) in [
        (
            "scalar-overwrite",
            json!({"type":"number"}),
            json!({"v":1}),
            json!({"v":2}),
        ),
        (
            "empty-patch-preserves",
            json!({"type":"string"}),
            json!({"v":"old"}),
            json!({}),
        ),
        (
            "object-replaced-not-merged",
            json!({"type":"object","fields":{"a":{"type":"optional","inner":{"type":"number"}},"b":{"type":"optional","inner":{"type":"number"}}}}),
            json!({"v":{"a":1,"b":2}}),
            json!({"v":{"a":3}}),
        ),
        (
            "array-replaced-not-concatenated",
            json!({"type":"array","element":{"type":"number"}}),
            json!({"v":[1,2]}),
            json!({"v":[3]}),
        ),
        (
            "empty-array-clears",
            json!({"type":"array","element":{"type":"number"}}),
            json!({"v":[1,2]}),
            json!({"v":[]}),
        ),
        (
            "optional-null-unsets",
            json!({"type":"optional","inner":{"type":"string"}}),
            json!({"v":"old"}),
            json!({"v":null}),
        ),
        (
            "optional-absent-unset-noop",
            json!({"type":"optional","inner":{"type":"string"}}),
            json!({}),
            json!({"v":null}),
        ),
        (
            "nullable-optional-preserves-null",
            json!({"type":"optional","inner":{"type":"any"}}),
            json!({"v":1}),
            json!({"v":null}),
        ),
        (
            "required-null-rejected",
            json!({"type":"number"}),
            json!({"v":1}),
            json!({"v":null}),
        ),
        (
            "wrong-kind-rejected",
            json!({"type":"number"}),
            json!({"v":1}),
            json!({"v":"2"}),
        ),
        (
            "unknown-key-rejected",
            json!({"type":"number"}),
            json!({"v":1}),
            json!({"other":2}),
        ),
        (
            "array-element-invalid",
            json!({"type":"array","element":{"type":"number"}}),
            json!({"v":[1]}),
            json!({"v":["2"]}),
        ),
    ] {
        let table_json = json!({"fields":{"v":ty}});
        let table: TableDef = serde_json::from_value(table_json.clone())?;
        let doc_map = doc.as_object().cloned().unwrap_or_default();
        let patch_map = patch.as_object().cloned().unwrap_or_default();
        let expect = outcome(apply_patch(&table, doc_map, &patch_map));
        rows.push(json!({"id":id,"table":table_json,"doc":doc,"patch":patch,"expect":expect}));
    }
    let mut out = serde_json::to_string_pretty(&json!({
        "$comment":"GENERATED by make gen-spec-patch-semantics using txn::apply_patch (including validate_value and whole-document validation). Objects and arrays replace at the top-level key. Null unsets only optional fields whose inner type rejects null.",
        "rows":rows
    }))?;
    out.push('\n');
    Ok(out)
}

fn outcome(result: Result<serde_json::Map<String, Value>, RtDbError>) -> Value {
    match result {
        Ok(doc) => json!({"doc":doc}),
        Err(error) => json!({"error":{"code":error.code}}),
    }
}
