//! Cursor codec fixtures computed by the production pagination primitives.

use crate::error::RtDbError;
use crate::pagination::{decode_cursor, encode_cursor};
use serde_json::json;

/// Render the cursor wire contract, including the ordered keyset tail.
pub fn render_cursor_encoding_spec() -> Result<String, RtDbError> {
    let mut rows = Vec::new();
    for (id, values) in [
        ("empty", json!([])),
        ("tiebreaker-only", json!([1700000000000_i64, "doc_a"])),
        (
            "index-and-tiebreakers",
            json!(["todo", 42, 1700000000000_i64, "doc_b"]),
        ),
        ("null-index", json!([null, 1700000000000_i64, "doc_c"])),
        (
            "boolean-index",
            json!([false, true, 1700000000000_i64, "doc_d"]),
        ),
        (
            "int64-decimal-index",
            json!(["9223372036854775807", 0, "doc_e"]),
        ),
        ("escaped-string-index", json!(["a/b\n\"c", 0, "doc_f"])),
        ("unicode-latin-index", json!(["é", 0, "doc_g"])),
        ("unicode-multibyte-index", json!(["東京😀", 0, "doc_h"])),
    ] {
        let values = values
            .as_array()
            .ok_or_else(|| RtDbError::internal("cursor fixture must be an array"))?;
        let token = encode_cursor(values)?;
        rows.push(
            json!({"id": id, "values": values, "cursor": token, "expect": decode_cursor(&token)?}),
        );
    }
    for (id, token) in [
        ("invalid-base64", "!!!not-base64!!!"),
        ("invalid-utf8", "/w=="),
        ("invalid-utf8-inside-string", "WyL/Il0="),
        ("invalid-json", "Ww=="),
        ("object-not-array", "e30="),
        ("null-not-array", "bnVsbA=="),
        ("string-not-array", "Ingi"),
    ] {
        let error = decode_cursor(token)
            .err()
            .ok_or_else(|| RtDbError::internal("invalid cursor fixture was accepted"))?;
        rows.push(json!({"id": id, "cursor": token, "error": {"code": error.code}}));
    }
    let mut out = serde_json::to_string_pretty(&json!({
        "$comment": "GENERATED by make gen-spec-cursor-encoding using server pagination::encode_cursor and decode_cursor. Scalar keysets preserve index values followed by created_at and id. Codec validation does not enforce query-specific arity or types (covered by pagination.json).",
        "rows": rows,
    })).map_err(|_| RtDbError::internal("failed to render cursor spec"))?;
    out.push('\n');
    Ok(out)
}
