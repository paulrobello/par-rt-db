//! Counter value and arithmetic decisions from production transaction helpers.
use crate::schema::FieldType;
use crate::txn::{counter_next, counter_value};
use serde_json::json;

/// Render safe-integer, bounds and non-numeric counter decisions.
pub fn render_counter_ops_spec() -> Result<String, serde_json::Error> {
    let mut rows = Vec::new();
    for (id, ty, current, delta, min, max) in [
        ("increment", FieldType::Number, json!(4), 3, None, None),
        ("decrement", FieldType::Number, json!(4), -3, None, None),
        ("zero-delta", FieldType::Number, json!(4), 0, None, None),
        (
            "minimum-inclusive",
            FieldType::Number,
            json!(4),
            -4,
            Some(0),
            Some(8),
        ),
        (
            "maximum-inclusive",
            FieldType::Number,
            json!(4),
            4,
            Some(0),
            Some(8),
        ),
        (
            "below-minimum-rejected-not-clamped",
            FieldType::Number,
            json!(4),
            -5,
            Some(0),
            Some(8),
        ),
        (
            "above-maximum-rejected-not-clamped",
            FieldType::Number,
            json!(4),
            5,
            Some(0),
            Some(8),
        ),
        (
            "safe-maximum",
            FieldType::Number,
            json!(9007199254740990_i64),
            1,
            None,
            None,
        ),
        (
            "safe-overflow-rejected",
            FieldType::Number,
            json!(9007199254740991_i64),
            1,
            None,
            None,
        ),
        (
            "safe-underflow-rejected",
            FieldType::Number,
            json!(-9007199254740991_i64),
            -1,
            None,
            None,
        ),
        (
            "fractional-current-rejected",
            FieldType::Number,
            json!(1.5),
            1,
            None,
            None,
        ),
        (
            "optional-null-rejected",
            FieldType::Optional {
                inner: Box::new(FieldType::Number),
            },
            json!(null),
            1,
            None,
            None,
        ),
        (
            "optional-number",
            FieldType::Optional {
                inner: Box::new(FieldType::Number),
            },
            json!(3),
            1,
            None,
            None,
        ),
    ] {
        let result = counter_value(&ty, &current, "v")
            .and_then(|value| counter_next(value, delta, min, max));
        let expect = match result {
            Ok(value) => json!({"value":value}),
            Err(error) => json!({"error":{"code":error.code}}),
        };
        rows.push(json!({"id":id,"fieldType":ty,"current":current,"delta":delta,"min":min,"max":max,"expect":expect}));
    }
    let mut out = serde_json::to_string_pretty(&json!({
        "$comment":"GENERATED by make gen-spec-counter-ops calling production txn::counter_value and counter_next, the same helpers step_adjust_counter uses. Bounds reject, never clamp. Argument admission and expected-field preconditions remain covered by the semantics corpus. Non-numeric strings and booleans are rejected at document validation before counter execution.",
        "rows":rows
    }))?;
    out.push('\n');
    Ok(out)
}
